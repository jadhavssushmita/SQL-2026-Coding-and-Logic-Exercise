-- BUSINESS QUESTION : Average number of distinct visits/sessions a user initiates over a given period 
-- TECHNICAL INTERPRETATION : SESSIONS PER USER
-- METRIC DEFINITION: SESSIONS PER USER = TOTAL SESSIONS / TOTAL USER

-- BUSINESS QUESTION: AVERAGE NUMBER OF INTERACTIONS PER USER
-- TECHNICAL INTERPRETATION: EVENTS PER USER
-- METRIC DEFINITION: TOTAL EVENTS / TOTAL ACTIVE USERS
-- In product analytics events per user measure total interaction volume / user efforts -- * 

SELECT 
  COUNT(DISTINCT session_id) AS total_sessions
, COUNT(DISTINCT user_id) AS total_users
, COUNT(event_type) AS total_event_interactions
, ROUND(COUNT(DISTINCT session_id) / COUNT(DISTINCT user_id),0) AS sessions_per_user
, ROUND(COUNT(event_type) / COUNT(DISTINCT user_id) ,0) AS events_per_user
, ROUND(COUNT(event_type) / COUNT(DISTINCT session_id), 0) AS event_per_session

FROM zillow_user_events;


